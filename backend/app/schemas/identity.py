from __future__ import annotations
from typing import Optional
from datetime import datetime
from pydantic import BaseModel, Field
from backend.app.schemas.confidence import IdentityStatus


class IdentityEvaluation(BaseModel):
    identity_status: IdentityStatus = Field(
        default=IdentityStatus.FAIL_UNSAFE_MERGE,
        description="Persistent identity gate evaluation status (e.g. FAIL_UNSAFE_MERGE)"
    )
    method_formal_identity_status: Optional[str] = Field(
        default="FAIL_UNSAFE_MERGE",
        description="Formal benchmark identity status (e.g. FAIL_UNSAFE_MERGE)"
    )
    method_formal_identity_evidence_basis: Optional[str] = Field(
        default="FORMAL_DENSE_GT",
        description="Evidence basis for formal methodology evaluation"
    )
    runtime_identity_status: Optional[str] = Field(
        default="UNVERIFIED_HEURISTIC_PASS",
        description="Runtime heuristic status for the current uploaded media"
    )
    runtime_identity_evidence_basis: Optional[str] = Field(
        default="RUNTIME_HEURISTIC_ONLY",
        description="Evidence basis for runtime upload heuristics"
    )
    player_level_analysis_allowed: bool = Field(
        default=False,
        description="Flag indicating whether player-specific tactical assessment is permitted"
    )
    withholding_reason: Optional[str] = Field(
        None,
        description="Explicit explanation when player-level conclusions are withheld"
    )
    expected_players: Optional[int] = Field(
        None,
        ge=1,
        description="Expected number of active players in the session"
    )
    raw_track_ids: int = Field(..., ge=0, description="Total raw track IDs generated by tracker")
    meaningful_identities: int = Field(..., ge=0, description="Consolidated meaningful identities")
    fragmentation_ratio: float = Field(..., ge=0.0, description="Ratio of meaningful IDs to active players")
    acceptance_threshold: float = Field(default=1.5, description="Maximum ratio for reliable persistent identity")
    evaluated_at: datetime = Field(default_factory=datetime.utcnow)
