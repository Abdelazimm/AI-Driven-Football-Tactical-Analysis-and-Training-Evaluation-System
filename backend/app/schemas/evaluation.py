"""
Evaluation metrics schema for scientific/engineering assessment of analysis runs.

CRITICAL: Unavailable metric != zero.
Use None to represent metrics that are not available, not computed, or not applicable.
Never substitute 0 for an unavailable metric value.
"""
from __future__ import annotations
from typing import Optional
from pydantic import BaseModel, Field


class DetectionEvaluationMetrics(BaseModel):
    """Object detection performance metrics."""
    precision: Optional[float] = Field(None, ge=0.0, le=1.0, description="Detection precision")
    recall: Optional[float] = Field(None, ge=0.0, le=1.0, description="Detection recall")
    map50: Optional[float] = Field(None, ge=0.0, le=1.0, description="mAP@IoU=0.50")
    map50_95: Optional[float] = Field(None, ge=0.0, le=1.0, description="mAP@IoU=0.50:0.95")


class IdentityTrackingEvaluationMetrics(BaseModel):
    """
    Identity and tracking metrics derived from the pipeline itself.
    These do NOT require external ground truth.
    """
    raw_track_count: Optional[int] = Field(None, ge=0, description="Total raw track IDs generated by tracker")
    final_identity_count: Optional[int] = Field(None, ge=0, description="Consolidated meaningful identities")
    fragmentation_ratio: Optional[float] = Field(None, ge=0.0, description="Ratio of raw IDs to meaningful identities")
    observation_retention: Optional[float] = Field(None, ge=0.0, le=1.0, description="Fraction of observations retained after filtering")
    track_coverage: Optional[float] = Field(None, ge=0.0, le=1.0, description="Fraction of frames with at least one active track")
    reentry_recovery_rate: Optional[float] = Field(None, ge=0.0, le=1.0, description="Success rate of re-identifying players after frame exit")


class GroundTruthTrackingMetrics(BaseModel):
    """
    Tracking metrics that require validated ground truth annotations.
    For normal user uploads without ground truth, all metric fields will be None
    and ground_truth_available will be False.
    """
    ground_truth_available: bool = Field(default=False, description="Whether validated GT annotations exist")
    hota: Optional[float] = Field(None, ge=0.0, le=1.0, description="Higher Order Tracking Accuracy")
    deta: Optional[float] = Field(None, ge=0.0, le=1.0, description="Detection Accuracy (HOTA decomposition)")
    assa: Optional[float] = Field(None, ge=0.0, le=1.0, description="Association Accuracy (HOTA decomposition)")
    idf1: Optional[float] = Field(None, ge=0.0, le=1.0, description="ID F1 Score")
    mota: Optional[float] = Field(None, description="Multiple Object Tracking Accuracy (can be negative)")
    id_switches: Optional[int] = Field(None, ge=0, description="Number of identity switches")
    false_positives: Optional[int] = Field(None, ge=0, description="Number of false positive detections")
    false_negatives: Optional[int] = Field(None, ge=0, description="Number of false negative detections")
    unavailable_reason: Optional[str] = Field(None, description="Explanation of why GT metrics are unavailable")


class EngineeringMetrics(BaseModel):
    """System engineering performance metrics for the analysis run."""
    runtime_seconds: Optional[float] = Field(None, ge=0.0, description="Total pipeline execution time")
    effective_fps: Optional[float] = Field(None, ge=0.0, description="Average frames processed per second")
    peak_gpu_memory_mb: Optional[float] = Field(None, ge=0.0, description="Peak GPU memory usage in MB")


class EvaluationMetrics(BaseModel):
    """
    Aggregate evaluation metrics for a complete analysis run.
    Separates detection, identity/tracking, GT-dependent, and engineering concerns.
    """
    detection: DetectionEvaluationMetrics = Field(default_factory=DetectionEvaluationMetrics)
    identity_tracking: IdentityTrackingEvaluationMetrics = Field(default_factory=IdentityTrackingEvaluationMetrics)
    ground_truth: GroundTruthTrackingMetrics = Field(default_factory=GroundTruthTrackingMetrics)
    engineering: EngineeringMetrics = Field(default_factory=EngineeringMetrics)
